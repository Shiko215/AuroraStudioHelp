window.numazuT = function (key) {
  const lang = window.numazuLang || 'zh';
  const pack = window.NUMAZU_I18N[lang] || window.NUMAZU_I18N.zh;
  return pack[key] || window.NUMAZU_I18N.en[key] || key;
};

window.numazuDisplayName = function (props) {
  const lang = window.numazuLang || 'zh';
  if (lang === 'ja' && props.name_ja) return props.name_ja;
  if (lang === 'en' && props.name_en) return props.name_en;
  if ((lang === 'zh' || lang === 'zh_cn') && props.name) return props.name;
  return props.name || props.name_ja || props.name_en || props.id || '';
};
